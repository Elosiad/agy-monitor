export function createPetTranslator(lang = 'zh-CN') {
  let current = lang === 'en' ? 'en' : 'zh-CN';
  const tr = (key, vars = {}) => {
    const pack = PET_DICT[current] || PET_DICT['zh-CN'];
    const raw = pack[key] ?? PET_DICT['zh-CN'][key] ?? key;
    if (!vars || typeof vars !== 'object') return raw;
    return String(raw).replace(/\{\{?(\w+)\}?\}/g, (_, k) =>
      Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : ''
    );
  };
  tr.setLang = (next) => {
    current = next === 'en' ? 'en' : 'zh-CN';
  };
  tr.getLang = () => current;
  return tr;
}
